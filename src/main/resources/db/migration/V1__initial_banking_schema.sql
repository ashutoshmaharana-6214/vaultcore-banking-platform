-- Clean-database baseline for VaultCore. Existing legacy demo volumes need an explicit migration.
CREATE TABLE customer_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_customer_email UNIQUE (email)
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(24) NOT NULL,
    holder_name VARCHAR(120) NOT NULL,
    balance NUMERIC(19,2) NOT NULL,
    owner_email VARCHAR(254),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_account_number UNIQUE (account_number),
    CONSTRAINT ck_account_balance_nonnegative CHECK (balance >= 0)
);
CREATE INDEX idx_accounts_owner ON accounts(owner_email, account_number);

CREATE TABLE bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(100),
    from_account VARCHAR(24) NOT NULL,
    to_account VARCHAR(24) NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_transfer_reference UNIQUE (reference),
    CONSTRAINT uk_transfer_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_transfer_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfer_accounts_differ CHECK (from_account <> to_account)
);
CREATE INDEX idx_tx_from_created ON bank_transactions(from_account, created_at DESC);
CREATE INDEX idx_tx_to_created ON bank_transactions(to_account, created_at DESC);

CREATE TABLE ledger_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(40) NOT NULL,
    account_number VARCHAR(24) NOT NULL,
    entry_type VARCHAR(6) NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_ledger_reference_leg UNIQUE (transaction_reference, entry_type),
    CONSTRAINT fk_ledger_transfer FOREIGN KEY (transaction_reference) REFERENCES bank_transactions(reference),
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_number) REFERENCES accounts(account_number),
    CONSTRAINT ck_ledger_entry_type CHECK (entry_type IN ('DEBIT','CREDIT')),
    CONSTRAINT ck_ledger_amount_positive CHECK (amount > 0)
);
CREATE INDEX idx_ledger_account ON ledger_postings(account_number, created_at);
CREATE INDEX idx_ledger_reference ON ledger_postings(transaction_reference);

-- Even if an application accidentally attempts to mutate entries, PostgreSQL rejects it.
CREATE FUNCTION reject_ledger_modification() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Ledger postings are append-only';
END;
$$;
CREATE TRIGGER ledger_postings_append_only
    BEFORE UPDATE OR DELETE ON ledger_postings
    FOR EACH ROW EXECUTE FUNCTION reject_ledger_modification();
